#!/usr/bin/env node
/**
 * 生成 src/types/api.ts 的唯一入口(api:generate / api:check 共用)。
 *
 * 默认走 openapi-typescript;仅对 JsonValue-Input / JsonValue-Output 两个递归
 * schema 用 transform 替换为模块级手写别名。原因:生成器把自递归 $ref 内联为
 * components["schemas"]["JsonValue-*"] 在自身注解里引用自己,会触发 TS2502,
 * 导致整个文件类型检查失败。
 *
 * 防漂移:替换前校验 OpenAPI 里 JsonValue 的 anyOf 形状(7 种类型 + 自递归
 * $ref);形状一旦变化本脚本即失败,手写别名不会与契约静默脱节。
 */
import { readFileSync, writeFileSync } from 'node:fs'
import openapiTS, { astToString } from 'openapi-typescript'
import ts from 'typescript'

const [input, output] = process.argv.slice(2)
if (!input || !output) {
  console.error('用法: node scripts/generate-api-types.mjs <openapi.json> <输出 api.ts>')
  process.exit(2)
}

const spec = JSON.parse(readFileSync(input, 'utf8'))

const EXPECTED_KINDS = ['string', 'integer', 'number', 'boolean', 'array', 'object', 'null']
const JSON_VALUE_ALIASES = {
  JsonValue: 'JsonValueInput',
  'JsonValue-Input': 'JsonValueInput',
  'JsonValue-Output': 'JsonValueOutput',
}

function assertJsonValueShape(name) {
  const node = spec.components?.schemas?.[name]
  const anyOf = node?.anyOf
  if (!Array.isArray(anyOf)) {
    throw new Error(`${name}: 缺少 anyOf,无法安全替换为手写别名`)
  }
  const kinds = new Set(anyOf.map((item) => item?.type))
  for (const kind of EXPECTED_KINDS) {
    if (!kinds.has(kind)) {
      throw new Error(`${name}: anyOf 缺少 ${kind}(实际:${[...kinds].join(',')})`)
    }
  }
  const self = `#/components/schemas/${name}`
  const arr = anyOf.find((item) => item?.type === 'array')
  const obj = anyOf.find((item) => item?.type === 'object')
  if (arr?.items?.$ref !== self || obj?.additionalProperties?.$ref !== self) {
    throw new Error(`${name}: 递归 $ref 形状变化,请同步更新手写别名`)
  }
}

for (const name of Object.keys(JSON_VALUE_ALIASES)) {
  assertJsonValueShape(name)
}

const inject = `
// 递归 JSON 值,与 OpenAPI JsonValue anyOf 等价(string|integer|number|boolean|
// array|object|null,数组/对象自递归)。由 generate-api-types.mjs 注入,替代生成器
// 对自递归 $ref 的内联展开(TS2502);禁止手改,形状受脚本校验。
export type JsonValueInput =
  | string
  | number
  | boolean
  | JsonValueInput[]
  | { [key: string]: JsonValueInput }
  | null;
// 与 JsonValueInput 同形(OpenAPI Output 方向)。
export type JsonValueOutput =
  | string
  | number
  | boolean
  | JsonValueOutput[]
  | { [key: string]: JsonValueOutput }
  | null;
`

const ast = await openapiTS(spec, {
  silent: true,
  inject,
  transform(_schemaObject, options) {
    for (const [name, alias] of Object.entries(JSON_VALUE_ALIASES)) {
      if (options.path === `#/components/schemas/${name}`) {
        return ts.factory.createTypeReferenceNode(alias)
      }
    }
    return undefined
  },
})

const header = `/**
 * This file was auto-generated by openapi-typescript (via scripts/generate-api-types.mjs).
 * Do not make direct changes to the file. 生成文件,禁止手改。
 */

`

writeFileSync(output, header + astToString(ast))
console.log(`generated: ${output}`)
